#!/usr/bin/env node
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..', '..');
const SRC_OFFLINE = path.join(ROOT, 'android-player', 'app', 'src', 'main', 'assets', 'offline');
const OUT = path.join(__dirname, '..', 'assets');
const OUT_OFFLINE = path.join(OUT, 'offline');
const CSP = "default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'";

fs.rmSync(OUT_OFFLINE, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT_OFFLINE, 'apps'), { recursive: true });

let player = fs.readFileSync(path.join(ROOT, 'public', 'player.html'), 'utf8');
const shim = '<script src="offline/apps-manifest.js"></script><script src="offline/offline-backend.js"></script>';
if (!player.includes('<head>')) throw new Error('player.html has no <head>');
player = player.replace('<head>', '<head>' + shim);
fs.writeFileSync(path.join(OUT, 'index.html'), player);

fs.copyFileSync(path.join(SRC_OFFLINE, 'offline-backend.js'), path.join(OUT_OFFLINE, 'offline-backend.js'));

const apps = JSON.parse(fs.readFileSync(path.join(SRC_OFFLINE, 'apps.json'), 'utf8'));
for (const a of apps) {
  if (!/^app_[0-9a-f]{12}$/.test(a.appId)) throw new Error('bad app id ' + a.appId);
  let html = fs.readFileSync(path.join(SRC_OFFLINE, 'apps', a.appId + '.html'), 'utf8');
  if (!/<head>/.test(html)) throw new Error(a.appId + ' has no <head>');
  html = html.replace('<head>', `<head><meta http-equiv="Content-Security-Policy" content="${CSP}">`);
  fs.writeFileSync(path.join(OUT_OFFLINE, 'apps', a.appId + '.html'), html);
}
fs.writeFileSync(path.join(OUT_OFFLINE, 'apps-manifest.js'),
  '// Generated by tools/sync_assets.js from apps.json. Read by offline-backend.js on file:// pages.\n' +
  'window.__ptvApps = ' + JSON.stringify(apps, null, 2) + ';\n');

console.log(`synced Player + ${apps.length} apps into ${path.relative(ROOT, OUT)}: ${apps.map(a => a.title).join(', ')}`);

const serverUrl = (process.env.PTV_SERVER_URL || '').trim().replace(/\/+$/, '');
if (serverUrl && !/^http:\/\/(localhost|127\.0\.0\.1):\d{2,5}$/.test(serverUrl)) {
  throw new Error('PTV_SERVER_URL must be http://localhost:<port> or http://127.0.0.1:<port>');
}
fs.writeFileSync(path.join(__dirname, '..', 'src', 'playerConfig.ts'),
  '// Generated by tools/sync_assets.js. Set PTV_SERVER_URL at build time for live mode.\n' +
  `export const SERVER_URL: string | null = ${serverUrl ? JSON.stringify(serverUrl) : 'null'};\n`);
console.log(serverUrl ? `live mode: Player from ${serverUrl}` : 'offline demo mode');
